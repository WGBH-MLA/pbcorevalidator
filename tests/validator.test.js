import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readdirSync, readFileSync } from 'node:fs';
import { DOMParser } from '@xmldom/xmldom';

import { runChecks } from '../js/checks.js';
import { decodeXml, declareUtf8, lineFinder, startTagLines } from '../js/xml.js';
import { parseXmllintOutput } from '../js/schema.js';

const fixtures = new URL('./fixtures/', import.meta.url);

function check(xml, options) {
  const doc = new DOMParser().parseFromString(xml, 'text/xml');
  return runChecks(doc, lineFinder(doc, xml), options);
}

// The .expected.json files were generated by running the original Ruby
// validator (libxml-ruby) over the matching .xml files with both optional
// validations enabled.
for (const name of readdirSync(fixtures).filter((f) => f.endsWith('.expected.json'))) {
  test(`matches the original Ruby validator: ${name.replace('.expected.json', '')}`, () => {
    const xml = readFileSync(new URL(name.replace('.expected.json', '.xml'), fixtures), 'utf8');
    const expected = JSON.parse(readFileSync(new URL(name, fixtures), 'utf8'));

    const actual = check(xml, { vocabs: true, bestPractices: true, version: '2.1' });

    assert.deepEqual(actual.bestPractices, expected.bestPractices);
    assert.deepEqual(actual.vocabs, expected.vocabs);
  });
}

test('only runs the checks that were requested', () => {
  const xml = readFileSync(new URL('pbcore-1x.xml', fixtures), 'utf8');

  assert.deepEqual(check(xml, { version: '2.1' }), { bestPractices: [], vocabs: [] });
  assert.equal(check(xml, { bestPractices: true, version: '2.1' }).vocabs.length, 0);

  // Vocabulary checks also report list-like values, grouped with best practices.
  const vocabOnly = check(xml, { vocabs: true, version: '2.1' });
  assert.equal(vocabOnly.vocabs.length, 9);
  assert.equal(vocabOnly.bestPractices.length, 1);
  assert.match(vocabOnly.bestPractices[0], /looks like it may be a list/);
});

test('skips best practices for PBCore 2.0, like the original', () => {
  const xml = readFileSync(new URL('pbcore-1x.xml', fixtures), 'utf8');
  assert.deepEqual(check(xml, { bestPractices: true, version: '2.0' }).bestPractices, []);
});

test('reports the line where an element start tag ends', () => {
  const xml = [
    '<?xml version="1.0"?>',            // 1
    '<!DOCTYPE a [',                     // 2
    '  <!ENTITY e "x > y">',             // 3
    ']>',                                // 4
    '<!-- <fake> -->',                   // 5
    '<a b="1 > 0">',                     // 6
    '  <![CDATA[ <fake> ]]>',            // 7
    '  <?pi <fake> ?>',                  // 8
    '  <b',                              // 9
    '     c="d"',                        // 10
    '     >text</b>',                    // 11
    '  <c/>',                            // 12
    '</a>',                              // 13
  ].join('\r\n');

  assert.deepEqual(startTagLines(xml), [6, 11, 12]);
});

test('decodes uploaded bytes by BOM, XML declaration, then UTF-8', () => {
  const latin1 = Uint8Array.from(Buffer.from('<?xml version="1.0" encoding="ISO-8859-1"?><a>caf\xe9</a>', 'latin1'));
  assert.match(decodeXml(latin1), /café/);

  const utf16 = Uint8Array.from(Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from('<a>café</a>', 'utf16le')]));
  assert.equal(decodeXml(utf16).replace(/^\uFEFF/, ''), '<a>café</a>');

  assert.equal(decodeXml(new TextEncoder().encode('<a>café</a>')), '<a>café</a>');
  assert.equal(decodeXml(new TextEncoder().encode('<?xml version="1.0" encoding="bogus"?><a>é</a>')), '<?xml version="1.0" encoding="bogus"?><a>é</a>');
});

test('pasted text is always treated as UTF-8', () => {
  assert.equal(declareUtf8('<?xml version="1.0" encoding=\'ISO-8859-1\'?><a/>'), '<?xml version="1.0" encoding=\'UTF-8\'?><a/>');
  assert.equal(declareUtf8('<a encoding="x"/>'), '<a encoding="x"/>');
});

test('parses xmllint output into schema and parse errors', () => {
  const output = [
    "input.xml:3: Schemas validity error : Element 'a': This element is not expected.",
    "input.xml:4: parser error : expected '>'",
    '  <b>text</b',
    '  ^',
    'input.xml:5: namespace error : Namespace prefix x is not defined',
    'input.xml:6: parser warning : xmlns: URI foo is not absolute',
    'input.xml fails to validate',
    '',
  ].join('\n');

  assert.deepEqual(parseXmllintOutput(output), {
    schemaErrors: ["Error: Element 'a': This element is not expected. at line 3."],
    parseErrors: [
      { message: "Fatal error: expected '>' at line 4.", fatal: true },
      { message: 'Error: Namespace prefix x is not defined at line 5.', fatal: false },
      { message: 'Warning: xmlns: URI foo is not absolute at line 6.', fatal: false },
    ],
  });
});
